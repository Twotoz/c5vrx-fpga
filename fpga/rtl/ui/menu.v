// Triversity: the menu, the live-view overlay, C5 status and the link to the
// C5s (LCD clock domain). Designed for three buttons:
//   live view   UP / DOWN previous / next channel (the channel pill lights
//               up for 2 s), SELECT opens the menu
//   menu        UP / DOWN move, SELECT opens or changes the item; on a value
//               (channel, mode, gain, aspect, brightness) SELECT starts editing: UP / DOWN
//               change it live, SELECT ends; SELECT held closes the menu
// Pages: 0 live view, 1 menu (Channel, Mode, Scan, Record, Receivers, Settings),
// 2 receivers (per C5 signal, C/N, gain, state; Back), 3 settings (Gain, AFC,
// Aspect, Logo, Brightness, Calibrate, Back). The look (grid, glyphs, page templates) is
// generated by fpga/gen/gen_osd.py, whose fill() is the reference for the
// field logic below; fpga/sim/run_osd_tb.py checks the LCD pixel for pixel.
//  - buttons: BUTTON markers from any C5 (C5 A has them) and the Tang's S2
//  - C5 status markers (gain, C/N, flags, channel, signal) per C5; the channel
//    in use is learned from C5 A's marker before the link starts sending
//  - scan: every channel 0.5 s, scored by the video's in-window sync edges
//  - renderer: one cell per clock from the page template into the cell RAM
//    ({bg[1:0], fg[2:0], glyph[6:0]}, read by lcd_out.v)
//  - link frames (c5/main/fpga_link.h) to link_tx.v
`default_nettype none
module menu #(parameter CLK_HZ = 33750000, parameter HAS_DVR = 1) (
    input  wire        clk,
    input  wire        rst,
    input  wire        mk_tog_a,         // markers (clk_a domain): toggle, source C5, payload
    input  wire [1:0]  mk_src_a,
    input  wire [15:0] mk_pl_a,
    input  wire        s1_n,             // Tang S1, active low: DOWN
    input  wire        s2_n,             // Tang S2, active low: SELECT (held: close)
    input  wire        locked_a,         // video (clk_a domain, slow)
    input  wire        pal_a,
    input  wire [15:0] sync_q_a,
    input  wire [1:0]  dvr_state_a,      // dvr.v: 0 no card, 1 ready, 2 recording, 3 error
    input  wire        wide_a,           // vid_sync: the camera signals 16:9
    input  wire [6:0]  fps_real_a,       // vid_sync: fields in the last second from a real vertical sync (slow, clk_a)
    input  wire [6:0]  fps_pred_a,       //   and fields the flywheel predicted
    output reg         osd_we,           // cell RAM write
    output reg  [10:0] osd_waddr,
    output reg  [11:0] osd_wdata,
    output reg         dvr,              // record video to the TF card
    output reg         lg,               // write the link log (Record: On = video + log, Log = log only)
    output reg  [1:0]  mode,             // fused C5s: 0 Single (A), 1 Diversity (A+B), 2 Triversity
    output wire [1:0]  hmode,            // lcd_out column map: 0 full width, 1 4:3, 2 Stretch
    output reg  [5:0]  channel,
    output reg         link_on,
    output reg         g_set, a_set,
    output wire [2:0]  gain_model,       // 0 LEVEL, 1 KEEL, 2 RSSI, 3 native, 4 restore Direct, 5 ULTRA (experimental)
    output reg         afc,
    output reg  [7:0]  f_seq,
    output reg         klock, async_on, nfilt,   // Signal page: keep lock, adaptive sync, noise filter
    output reg  [1:0]  rescue,           // Signal page: rescue PLL 0 Off, 1 Auto, 2 On, 3 experimental D3
    output wire [1:0]  hz90,             // 90 Hz HDMI build, Settings: 0 Free, 1 Camera, 2 Smooth
    output reg         boot,             // the start-up screen is up (lcd_out.v draws the logo)
    output reg         bl_pwm
);
`ifdef TRI_HDMI90
`define TRI_MENU_H90
`endif
`ifdef TRI_MENU_H90
    localparam H90 = 1;
`else
    localparam H90 = 0;
`endif
    // the start-up screen: the build and its version (fpga/build.sh: the git commit)
`ifndef TRI_VERSION
`define TRI_VERSION 28'h0000000
`endif
    localparam [27:0] VER = `TRI_VERSION;
`ifdef TRI_HDMI90
    localparam [71:0] BUILD_S = "HDMI 90Hz";
`elsif TRI_HDMI
    localparam [71:0] BUILD_S = "     HDMI";
`else
    localparam [71:0] BUILD_S = "      LCD";
`endif
    // ---- glyphs, colours, fields (gen_osd.py) ------------------------------------
    localparam [6:0] G_LOGO0 = 22,
                     G_CAPL = 1, G_CAPR = 2, G_DOT = 8, G_CHL = 9, G_CHR = 10, G_BARS = 13, G_SEGON = 18,
                     G_SEGOFF = 19, G_MID = 20, G_CHECK = 21, SP = 32;
    localparam [2:0] WHITE = 0, GREY = 1, ACCENT = 2, RED = 3, GREEN = 4, AMBER = 5, DARKFG = 6, PANELFG = 7;
    localparam [1:0] BG_VIDEO = 0, BG_PANEL = 1, BG_BAR = 2, BG_DARK = 3;
    localparam [5:0] F_CAPL = 1, F_CAPR = 2, F_LIVECH = 3, F_REC = 4, F_NOSIG = 5, F_RXBAR = 6, F_VSTD = 7, F_CHVAL = 8,
                     F_SCANV = 9, F_RECV = 10, F_RXCNT = 11, F_RXROW = 12, F_GAINV = 13, F_AFCV = 14, F_BRIGHTV = 15,
                     F_CALV = 16, F_EDL = 17, F_EDR = 18, F_MODEV = 19,
                     F_ASPV = 20, F_LOGOV = 21, F_LOGO = 22, F_KLOCKV = 23, F_ASYNCV = 24, F_RESCV = 25, F_SPIKEV = 26, F_WEAKV = 27, F_NFILTV = 28, F_HZ90V = 29,
                     F_BOOTBLD = 30, F_BOOTVER = 31, F_BOOTRX = 32, F_BOOTSD = 33, F_NATIVEV = 34, F_VIDFPS = 35;
    localparam [4:0] ITEM0 = 5'd7;
    // ---- slow clock ---------------------------------------------------------------
    localparam MS = CLK_HZ / 1000;
    reg [15:0] mscnt; reg ms;
    always @(posedge clk) begin
        ms <= 1'b0;
        if (rst) mscnt <= 16'd0;
        else if (mscnt == MS - 1) begin mscnt <= 16'd0; ms <= 1'b1; end else mscnt <= mscnt + 16'd1;
    end
    // ---- clock-domain crossing of the markers and the video status ----------------
    reg [1:0] wd;
    reg [2:0] mt; reg [1:0] lk, pl; reg [15:0] sq1, sq2; reg [1:0] ds1, ds2;
    reg [6:0] fr1, fr2, fp1, fp2;        // fields per second (changes once a second: two flops are enough)
    always @(posedge clk) begin
        mt <= {mt[1:0], mk_tog_a}; lk <= {lk[0], locked_a}; pl <= {pl[0], pal_a}; sq1 <= sync_q_a; sq2 <= sq1;
        fr1 <= fps_real_a; fr2 <= fr1; fp1 <= fps_pred_a; fp2 <= fp1;
        ds1 <= dvr_state_a; ds2 <= ds1; wd <= {wd[0], wide_a};
    end
    wire mk_ev = mt[2] ^ mt[1];          // payload/source stable for ~250 ms after a toggle
    wire locked = lk[1], pal = pl[1];
    // ---- C5 status ------------------------------------------------------------------
    reg [7:0]  st_gain [0:2];
    reg [11:0] st_cn [0:2];
    reg [7:0]  st_flags [0:2];
    reg [6:0]  st_sig [0:2];
    reg [1:0] direct_model;              // 0 Level, 1 Keel, 2 RSSI, 3 Ultra (link 'G' 5)
    reg native_requested, owner_set;
    assign gain_model = owner_set ? (native_requested ? 3'd3 : 3'd4) : direct_model == 2'd3 ? 3'd5 : {1'b0, direct_model};
    reg [11:0] owner_age [0:2];           // age of the actual mode, independently of other markers
    reg [11:0] st_age [0:2];             // ms since the last marker, saturating
    reg [3:0]  btn; reg btn_ev;
    integer k;
    always @(posedge clk) begin
        btn_ev <= 1'b0;
        if (rst) begin
            for (k = 0; k < 3; k = k + 1) begin owner_age[k] <= 12'hfff; st_age[k] <= 12'hfff; st_sig[k] <= 7'd0; st_gain[k] <= 8'd0; st_cn[k] <= 12'd0; st_flags[k] <= 8'd0; end
        end else begin
            if (ms) for (k = 0; k < 3; k = k + 1) begin
                if (st_age[k] != 12'hfff) st_age[k] <= st_age[k] + 12'd1;
                if (owner_age[k] != 12'hfff) owner_age[k] <= owner_age[k] + 12'd1;
            end
            if (mk_ev && mk_src_a != 2'd3) begin
                st_age[mk_src_a] <= 12'd0;
                case (mk_pl_a[15:12])
                    4'd1: begin btn <= mk_pl_a[3:0] | {mk_pl_a[4], 3'b0}; btn_ev <= 1'b1; end
                    4'd2: st_gain[mk_src_a] <= mk_pl_a[7:0];
                    4'd3: st_cn[mk_src_a] <= mk_pl_a[11:0];
                    4'd4: begin st_flags[mk_src_a] <= mk_pl_a[7:0]; owner_age[mk_src_a] <= 12'd0; end
                    4'd6: st_sig[mk_src_a] <= mk_pl_a[6:0] > 7'd100 ? 7'd100 : mk_pl_a[6:0];
                    default: ;
                endcase
            end
        end
    end
    wire [2:0] fresh = {st_age[2] < 12'd3000, st_age[1] < 12'd3000, st_age[0] < 12'd3000};
    wire [2:0] owner_fresh = {owner_age[2] < 12'd3000, owner_age[1] < 12'd3000, owner_age[0] < 12'd3000};
    wire [2:0] native_applied = owner_fresh & {st_flags[2][7], st_flags[1][7], st_flags[0][7]};
    wire native_value = owner_set ? native_requested : |native_applied;
    wire native_pending = owner_set && (!(|fresh) ||
        |(fresh & (~owner_fresh | (native_applied ^ {3{native_requested}}))));
    // a C5 that works: heard, and not reporting its DC fault (flags bit 3)
    wire [2:0] c5ok = fresh & ~{st_flags[2][3], st_flags[1][3], st_flags[0][3]};
    // ---- Tang S2: debounced SELECT (short) / SELECT long (0.6 s) ----------------------
    reg [1:0] s2s; reg [9:0] s2_ms; reg s2_long_done; reg s2_ev; reg [3:0] s2_btn;
    always @(posedge clk) begin
        s2s <= {s2s[0], ~s2_n}; s2_ev <= 1'b0;
        if (rst) begin s2_ms <= 10'd0; s2_long_done <= 1'b0; end
        else if (ms) begin
            if (s2s[1]) begin
                if (s2_ms != 10'h3ff) s2_ms <= s2_ms + 10'd1;
                if (s2_ms == 10'd600 && !s2_long_done) begin s2_long_done <= 1'b1; s2_ev <= 1'b1; s2_btn <= 4'b1010; end
            end else begin
                if (s2_ms >= 10'd30 && !s2_long_done) begin s2_ev <= 1'b1; s2_btn <= 4'b0010; end
                s2_ms <= 10'd0; s2_long_done <= 1'b0;
            end
        end
    end
    // ---- Tang S1: debounced DOWN (with S2 and the Exit item the menu works without C5 A's buttons) ----
    reg [1:0] s1s; reg [5:0] s1_ms; reg s1_ev;
    always @(posedge clk) begin
        s1s <= {s1s[0], ~s1_n}; s1_ev <= 1'b0;
        if (rst) s1_ms <= 6'd0;
        else if (ms) begin
            if (s1s[1]) begin if (s1_ms != 6'h3f) s1_ms <= s1_ms + 6'd1; end
            else begin if (s1_ms >= 6'd30) s1_ev <= 1'b1; s1_ms <= 6'd0; end
        end
    end
    // ---- menu state -------------------------------------------------------------------
    reg        open, edit, scanning;
    reg [2:0]  page;                      // 1 menu, 2 receivers, 3 settings, 4 signal (while open)
    reg [2:0]  cursor;
    reg [2:0]  bright;
    reg [1:0]  hz90_r;                    // 90 Hz HDMI build: 0 Free, 1 Camera, 2 Smooth
    assign hz90 = hz90_r;
    reg [1:0]  aspect;                    // 0 4:3, 1 16:9, 2 Stretch, 3 Auto
    reg        logo;                      // small logo in the live view
    reg [5:0]  scan_ch, best_ch, orig_ch;
    reg [15:0] best_q;
    reg [9:0]  scan_ms;
    reg [10:0] toast_ms;                  // channel pill highlight after a live change
    reg [11:0] cal_ms;                    // "Sent" after Calibrate
    reg [9:0]  sec_ms;
    reg [3:0]  rm_t, rm_o, rs_o; reg [2:0] rs_t;    // recording time, BCD (mm:ss, minutes stop at 99)
    wire       ev = btn_ev | s2_ev | s1_ev;
    // start-up screen: at least 1 s, then until there is video (or SELECT), at most 3 s
    reg  [11:0] boot_ms; reg bskip;
    wire [3:0] b  = btn_ev ? btn : s2_ev ? s2_btn : 4'b0100;       // bit 0 UP, 1 SELECT, 2 DOWN, 3 long
    wire       up = b[0], sel = b[1] && !b[3], dn = b[2], hold = b[1] && b[3];
    wire [5:0] ch_next = channel == 6'd47 ? 6'd0 : channel + 6'd1;
    wire [5:0] ch_prev = channel == 6'd0 ? 6'd47 : channel - 6'd1;
    wire [3:0] n_items = page == 3'd2 ? 4'd1 : page == 3'd4 ? 4'd6 : page == 3'd1 ? 4'd8 : 4'd7;
    always @(posedge clk) begin
        if (rst) begin
            // Signal defaults (board 2026-11-26): Keep lock, Adaptive sync, Noise filter on, Rescue On
            open <= 1'b0; edit <= 1'b0; page <= 3'd1; klock <= 1'b1; async_on <= 1'b1; nfilt <= 1'b1; rescue <= 2'd2; cursor <= 3'd0; bright <= 3'd7; hz90_r <= 2'd0; aspect <= 2'd3; logo <= 1'b1; dvr <= 1'b0; lg <= 1'b0; mode <= 2'd2; channel <= 6'd8;
            link_on <= 1'b0; g_set <= 1'b0; a_set <= 1'b0; direct_model <= 2'd0; native_requested <= 1'b0; owner_set <= 1'b0; afc <= 1'b1; f_seq <= 8'd0;
            scanning <= 1'b0; toast_ms <= 11'd0; cal_ms <= 12'd0; sec_ms <= 10'd0; rm_t <= 4'd0; rm_o <= 4'd0; rs_t <= 3'd0; rs_o <= 4'd0;
            boot <= 1'b1; boot_ms <= 12'd0; bskip <= 1'b0;
        end else begin
            if (boot && ms) begin
                boot_ms <= boot_ms + 12'd1;
                if ((boot_ms >= 12'd1000 && (locked || bskip)) || boot_ms >= 12'd3000) begin
                    boot <= 1'b0;
                    // a C5 missing or faulty: fall back to what the working ones can do
                    if (!(c5ok[0] && c5ok[1] && c5ok[2])) mode <= (c5ok[0] && c5ok[1]) ? 2'd1 : 2'd0;
                end
            end
            if (ms && toast_ms != 11'd0) toast_ms <= toast_ms - 11'd1;
            if (ms && cal_ms != 12'd0) cal_ms <= cal_ms - 12'd1;
            // recording time
            if (!(dvr && ds2 == 2'd2)) begin sec_ms <= 10'd0; rm_t <= 4'd0; rm_o <= 4'd0; rs_t <= 3'd0; rs_o <= 4'd0; end
            else if (ms) begin
                if (sec_ms == 10'd999) begin
                    sec_ms <= 10'd0;
                    if (rs_o != 4'd9) rs_o <= rs_o + 4'd1;
                    else begin
                        rs_o <= 4'd0;
                        if (rs_t != 3'd5) rs_t <= rs_t + 3'd1;
                        else begin
                            rs_t <= 3'd0;
                            if (rm_o != 4'd9) rm_o <= rm_o + 4'd1;
                            else if (rm_t != 4'd9) begin rm_o <= 4'd0; rm_t <= rm_t + 4'd1; end
                        end
                    end
                end else sec_ms <= sec_ms + 10'd1;
            end
            if (mk_ev && mk_pl_a[15:12] == 4'd5 && mk_src_a == 2'd0 && !link_on && mk_pl_a[5:0] < 6'd48)
                begin channel <= mk_pl_a[5:0]; link_on <= 1'b1; end
            if (scanning) begin
                if (ms) scan_ms <= scan_ms + 10'd1;
                if (scan_ms == 10'd500) begin
                    if (sq2 > best_q) begin best_q <= sq2; best_ch <= scan_ch; end
                    scan_ms <= 10'd0;
                    if (scan_ch == 6'd47) begin
                        scanning <= 1'b0;
                        channel <= (sq2 > best_q ? sq2 : best_q) > 16'd500 ? (sq2 > best_q ? scan_ch : best_ch) : orig_ch;
                    end else begin scan_ch <= scan_ch + 6'd1; channel <= scan_ch + 6'd1; end
                end
            end
            if (ev && boot) begin if (sel) bskip <= 1'b1; end   // buttons during the start-up screen: SELECT skips it
            else if (ev) begin
                link_on <= 1'b1;
                if (!open) begin
                    if (sel) begin open <= 1'b1; page <= 3'd1; cursor <= 3'd0; edit <= 1'b0; end
                    else if (up && !scanning) begin channel <= ch_next; toast_ms <= 11'd2000; end
                    else if (dn && !scanning) begin channel <= ch_prev; toast_ms <= 11'd2000; end
                end else if (hold) begin open <= 1'b0; edit <= 1'b0; end
                else if (edit) begin                                   // change the value live
                    if (sel) edit <= 1'b0;
                    else if (page == 3'd1 && cursor == 3'd0) channel <= up ? ch_next : dn ? ch_prev : channel;
                    else if (page == 3'd1) begin
                        if (up) mode <= mode == 2'd2 ? 2'd0 : mode + 2'd1;
                        if (dn) mode <= mode == 2'd0 ? 2'd2 : mode - 2'd1;
                    end
                    else if (cursor == 3'd0) begin
                        if (up) direct_model <= direct_model + 2'd1;     // Level, Keel, RSSI, Ultra
                        if (dn) direct_model <= direct_model - 2'd1;
                        owner_set <= 1'b0; g_set <= 1'b1;
                    end else if (cursor == 3'd2) begin
                        if (up) aspect <= aspect + 2'd1;
                        if (dn) aspect <= aspect - 2'd1;
                    end else begin
                        if (up && bright != 3'd7) bright <= bright + 3'd1;
                        if (dn && bright != 3'd0) bright <= bright - 3'd1;
                    end
                end else if (up) cursor <= cursor == 3'd0 ? n_items - 3'd1 : cursor - 3'd1;
                else if (dn) cursor <= cursor == n_items - 3'd1 ? 3'd0 : cursor + 3'd1;
                else if (sel) case (page)
                    3'd1: case (cursor)
                        3'd0: if (!scanning) edit <= 1'b1;
                        3'd1: edit <= 1'b1;
                        3'd2: if (scanning) begin scanning <= 1'b0; channel <= orig_ch; end
                              else begin scanning <= 1'b1; scan_ch <= 6'd0; channel <= 6'd0; orig_ch <= channel; best_q <= 16'd0; scan_ms <= 10'd0; end
                        3'd3: if (HAS_DVR != 0) begin dvr <= !dvr && !lg; lg <= !lg || dvr; end   // Off -> On -> Log -> Off
                        3'd4: begin page <= 3'd2; cursor <= 3'd0; end
                        3'd5: begin page <= 3'd4; cursor <= 3'd0; end
                        3'd6: begin page <= 3'd3; cursor <= 3'd0; end
                        default: begin open <= 1'b0; edit <= 1'b0; end      // Exit
                    endcase
                    3'd2: begin page <= 3'd1; cursor <= 3'd4; end
                    3'd4: case (cursor)
                        3'd0: klock <= ~klock;
                        3'd1: async_on <= ~async_on;
                        3'd2: nfilt <= ~nfilt;
                        3'd3: rescue <= rescue + 2'd1;
                        3'd4: begin
                            native_requested <= ~(owner_set ? native_requested : |native_applied);
                            owner_set <= 1'b1; g_set <= 1'b1;
                        end
                        default: begin page <= 3'd1; cursor <= 3'd5; end
                    endcase
                    default: case (cursor)
                        3'd0: if (!native_value) edit <= 1'b1;
                        3'd2: edit <= 1'b1;
                        3'd4: if (H90) hz90_r <= hz90_r == 2'd2 ? 2'd0 : hz90_r + 2'd1;   // Free -> Camera -> Smooth
                              else edit <= 1'b1;
                        3'd1: begin afc <= ~afc; a_set <= 1'b1; end
                        3'd3: logo <= ~logo;
                        3'd5: if (!native_value) begin f_seq <= f_seq + 8'd1; cal_ms <= 12'd3000; end
                        default: begin page <= 3'd1; cursor <= 3'd6; end
                    endcase
                endcase
            end
        end
    end
    assign hmode = aspect == 2'd0 ? 2'd1 : aspect == 2'd1 ? 2'd0 : aspect == 2'd2 ? 2'd2 : (wd[1] ? 2'd0 : 2'd1);
    // ---- backlight ------------------------------------------------------------------------
    reg [10:0] pw;
    // Eight evenly spaced levels, from 160/1280 to continuously on.
    wire [10:0] bl_duty = 11'd160 + {bright, 7'd0} + {bright, 5'd0};
    always @(posedge clk) begin
        if (rst || pw == 11'd1279) pw <= 11'd0;
        else pw <= pw + 11'd1;
        bl_pwm <= pw < bl_duty;
    end
    // ---- renderer: template -> fields -> cell RAM --------------------------------------
    reg [17:0] tmpl [0:6995];                      // five pages, then the start-up screen's rows 10..15
    reg [15:0] freq [0:47];
`ifdef TRI_MENU_H90
`include "osd_pages_h90.vh"
`else
`include "osd_pages.vh"
`endif
    reg [10:0] ra; reg [6:0] rc; reg [4:0] rr;      // cell address, column, row
    reg [12:0] pbase;                               // page * 1320
    reg [17:0] tw_t; reg tw_sel; reg [10:0] wa1; reg [4:0] rr1;
    wire [17:0] tw = tw_sel ? 18'd0 : tw_t;    // the template ROM's read stays a plain block-RAM read
    reg [15:0] fq;
    wire [2:0] pg = open ? page : 3'd0;
    always @(posedge clk) begin
        ra <= (rst || ra == 11'd1319) ? 11'd0 : ra + 11'd1;
        if (rst || ra == 11'd1319) begin rc <= 7'd0; rr <= 5'd0; pbase <= boot ? 13'd5940 : pg == 3'd0 ? 13'd0 : pg == 3'd1 ? 13'd1320 : pg == 3'd2 ? 13'd2640 : pg == 3'd3 ? 13'd3960 : 13'd5280; end
        else if (rc == 7'd65) begin rc <= 7'd0; rr <= rr + 5'd1; end else rc <= rc + 7'd1;
        // the start-up screen has rows 10..15 only (after the five pages)
        tw_t <= tmpl[pbase + {2'b0, ra}]; tw_sel <= boot && (rr < 5'd10 || rr > 5'd15); wa1 <= ra; rr1 <= rr; fq <= freq[channel];
    end
    // ---- field logic (gen_osd.py field_cells) ----
    function [7:0] digit; input [3:0] d; digit = 8'd48 + d; endfunction
    function [6:0] hexd; input [3:0] d; hexd = d < 4'd10 ? 7'd48 + {3'd0, d} : 7'd87 + {3'd0, d}; endfunction
    function [3:0] tv; input [7:0] v;    // tens of v (0..99)
        tv = v >= 8'd90 ? 4'd9 : v >= 8'd80 ? 4'd8 : v >= 8'd70 ? 4'd7 : v >= 8'd60 ? 4'd6 : v >= 8'd50 ? 4'd5 :
             v >= 8'd40 ? 4'd4 : v >= 8'd30 ? 4'd3 : v >= 8'd20 ? 4'd2 : v >= 8'd10 ? 4'd1 : 4'd0;
    endfunction
    function [3:0] ov; input [7:0] v; ov = v - {tv(v), 3'b0} - {tv(v), 1'b0}; endfunction
    function [6:0] str; input [4:0] sel; input [3:0] i;    // right-justified fixed strings
        reg [8*9-1:0] s;
        begin
            case (sel)
                19: s = "      4:3"; 20: s = "     16:9"; 21: s = "  Stretch"; 22: s = " Auto 4:3"; 23: s = "Auto 16:9";
                16: s = "   Single"; 17: s = "Diversity"; 18: s = "riversity";
                0: s = " No video"; 1: s = "      PAL"; 2: s = "     NTSC"; 3: s = "      Off"; 4: s = "  No card";
                5: s = "    Ready"; 6: s = " Card err"; 7: s = "    Level"; 8: s = "     Keel"; 9: s = "     RSSI";
                10: s = "       On"; 11: s = "      Off"; 12: s = "     Sent"; 13: s = "NO SIGNAL"; 14: s = "     REC ";
                15: s = "     Off "; 24: s = "   No DVR"; 25: s = "      Log"; 26: s = "     Auto";
                27: s = "     Free"; 28: s = "   Camera"; 29: s = "   Smooth"; 30: s = BUILD_S; 31: s = "    Ultra";
                default: s = "         ";
            endcase
            str = s[8 * (8 - i) +: 7];
        end
    endfunction
    wire [5:0] fid = tw[12:7];
    wire [6:0] fi  = tw[6:0];
    wire [4:0] sel_row = open ? (page == 3'd2 ? ITEM0 + 5'd4 : ITEM0 + {2'b0, cursor}) : (toast_ms != 11'd0 ? 5'd1 : 5'd31);
    wire       is_sel = rr1 == sel_row;
    wire       is_edit = is_sel && edit && open;
    wire [1:0] nact = {1'b0, fresh[0]} + {1'b0, fresh[1]} + {1'b0, fresh[2]};
    // per-row C5 (receivers page) and per-slot C5 (live bars)
    wire [1:0] rk  = rr1 - ITEM0;
    wire [1:0] bk  = fi < 7'd5 ? 2'd0 : fi < 7'd9 ? 2'd1 : 2'd2;
    // C/N whole dB of C5 rk: magnitude rounded, sign
    wire [11:0] cnr = st_cn[rk];
    wire        cn_neg = cnr < 12'd1000;
    wire [11:0] cn_mag = cn_neg ? 12'd1000 - cnr : cnr - 12'd1000;
    wire [9:0]  cn_c = cn_mag > 12'd994 ? 10'd994 : cn_mag[9:0];    // 99.4 dB and up show 99
    wire [17:0] cn_x = {8'd0, cn_c} + 18'd5;
    wire [17:0] cn_p = (cn_x << 7) + (cn_x << 6) + (cn_x << 3) + (cn_x << 2) + cn_x;    // * 205
    wire [7:0]  cn_db = {1'b0, cn_p[17:11]};
    wire [7:0]  gn = st_gain[rk] > 8'd99 ? 8'd99 : st_gain[rk];
    // one decimal converter for the number this cell shows (one cell a clock):
    // the scan step, the recording minutes, C/N or gain; seconds have their own
    wire [6:0]  fr99 = fr2 > 7'd99 ? 7'd99 : fr2, fp99 = fp2 > 7'd99 ? 7'd99 : fp2;
    wire [7:0]  nv = fid == F_SCANV ? {2'b0, scan_ch} + 8'd1 :
                     fid == F_VIDFPS ? {1'b0, fi <= 7'd7 ? fr99 : fp99} :
                     (fid == F_RXROW && fi <= 7'd14) ? cn_db : gn;
    wire [3:0]  T = tv(nv), O = ov(nv);
    reg  [6:0]  fch; reg fgv, fbv; reg [2:0] ffg; reg [1:0] fbg;
    // the fixed strings: a field picks one and the character (ss, si); one str() lookup for all
    reg  [4:0]  ss; reg [3:0] si; reg su;
    reg  [6:0]  bo; reg [1:0] bg_k;
    always @(*) begin
        fch = fi; fgv = 1'b0; ffg = WHITE; fbv = 1'b0; fbg = BG_VIDEO; ss = 5'd31; si = 4'd0; su = 1'b0; bo = 7'd0; bg_k = 2'd0;
        case (fid)
            6'd0: fch = fi;
            F_CAPL, F_CAPR: begin
                fch = fid == F_CAPL ? G_CAPL : G_CAPR; fgv = 1'b1;
                ffg = is_edit ? DARKFG : is_sel ? ACCENT : PANELFG;
            end
            F_EDL, F_EDR: fch = is_edit ? (fid == F_EDL ? G_CHL : G_CHR) : SP;
            F_LIVECH, F_CHVAL: case (fi)
                7'd0: fch = channel[5:3] == 3'd0 ? "R" : channel[5:3] == 3'd1 ? "A" : channel[5:3] == 3'd2 ? "B" :
                            channel[5:3] == 3'd3 ? "E" : channel[5:3] == 3'd4 ? "F" : "L";
                7'd1: fch = digit({1'b0, channel[2:0]} + 4'd1);
                7'd3: fch = G_MID;
                7'd5: fch = digit(fq[15:12]); 7'd6: fch = digit(fq[11:8]); 7'd7: fch = digit(fq[7:4]); 7'd8: fch = digit(fq[3:0]);
                default: fch = SP;
            endcase
            F_VSTD: begin ss = !locked ? 5'd0 : pal ? 5'd1 : 5'd2; si = fi[3:0] + 4'd1; su = 1'b1; end
            F_SCANV: begin
                fch = SP;
                if (scanning) case (fi)
                    7'd0: fch = G_SEGON;
                    7'd1: fch = scan_ch >= 6'd9  ? G_SEGON : G_SEGOFF;
                    7'd2: fch = scan_ch >= 6'd19 ? G_SEGON : G_SEGOFF;
                    7'd3: fch = scan_ch >= 6'd28 ? G_SEGON : G_SEGOFF;
                    7'd4: fch = scan_ch >= 6'd38 ? G_SEGON : G_SEGOFF;
                    7'd6: fch = scan_ch >= 6'd9 ? digit(T) : SP;
                    7'd7: fch = digit(scan_ch >= 6'd9 ? O : scan_ch[3:0] + 4'd1);
                    7'd8: fch = "/"; 7'd9: fch = "4"; 7'd10: fch = "8";
                    default: fch = SP;
                endcase
            end
            F_RECV: begin
                if (HAS_DVR == 0) begin ss = 5'd24; si = fi[3:0]; su = 1'b1; fch = SP; end
                else if (!dvr) begin ss = !lg ? 5'd3 : ds2 == 2'd0 ? 5'd4 : ds2 == 2'd3 ? 5'd6 : 5'd25; si = fi[3:0]; su = 1'b1; fch = SP; end
                else if (ds2 == 2'd2) case (fi)
                    7'd2: fch = rm_t != 4'd0 ? G_DOT : SP;
                    7'd3: fch = rm_t != 4'd0 ? SP : G_DOT;
                    7'd4: fch = rm_t != 4'd0 ? digit(rm_t) : SP;
                    7'd5: fch = digit(rm_o);
                    7'd6: fch = ":";
                    7'd7: fch = digit({1'b0, rs_t}); 7'd8: fch = digit(rs_o);
                    default: fch = SP;
                endcase
                else begin ss = ds2 == 2'd0 ? 5'd4 : ds2 == 2'd1 ? 5'd5 : 5'd6; si = fi[3:0]; su = 1'b1; fch = SP; end
                if ((dvr || lg) && ((ds2 == 2'd2 && fch == G_DOT) || ds2 == 2'd3)) begin fgv = 1'b1; ffg = RED; end
            end
            F_MODEV: if (fi == 7'd0) fch = mode == 2'd2 ? "T" : SP;
                     else begin ss = mode == 2'd2 ? 5'd18 : 5'd16 + {3'd0, mode}; si = fi[3:0] - 4'd1; su = 1'b1; end
            F_ASPV:  begin ss = aspect == 2'd3 ? (wd[1] ? 5'd23 : 5'd22) : 5'd19 + {3'd0, aspect}; si = fi[3:0]; su = 1'b1; end
            F_LOGOV: begin ss = logo ? 5'd10 : 5'd11; si = fi[3:0] + 4'd6; su = 1'b1; end
            F_LOGO: begin
                if (!logo) begin fch = 7'd0; fbv = 1'b1; fbg = BG_VIDEO; end
                else if (fi == 7'd0 || fi == 7'd11) begin fch = fi == 7'd0 ? G_CAPL : G_CAPR; fgv = 1'b1; ffg = PANELFG; fbv = 1'b1; fbg = BG_VIDEO; end
                else begin fch = G_LOGO0 + fi - 7'd1; fgv = 1'b1; ffg = fi <= 7'd4 ? ACCENT : WHITE; end
            end
            F_RXCNT: fch = fi == 7'd0 ? digit({2'b0, nact}) : fi == 7'd1 ? "/" : "3";
            F_GAINV: begin ss = direct_model == 2'd3 ? 5'd31 : 5'd7 + {3'd0, direct_model}; si = fi[3:0] + 4'd4; su = 1'b1; end
            F_AFCV:  begin ss = afc ? 5'd10 : 5'd11; si = fi[3:0] + 4'd6; su = 1'b1; end
            F_KLOCKV, F_ASYNCV, F_NFILTV:
                     begin ss = (fid == F_KLOCKV ? klock : fid == F_ASYNCV ? async_on : nfilt) ? 5'd10 : 5'd11; si = fi[3:0] + 4'd6; su = 1'b1; end
            F_NATIVEV: begin
                if (fi == 7'd4) begin fch = native_pending ? "?" : SP; fgv = 1'b1; ffg = AMBER; end
                else begin ss = native_value ? 5'd10 : 5'd11; si = fi[3:0] + 4'd5; su = 1'b1; end
            end
            F_RESCV: if (rescue == 2'd3) fch = fi == 7'd1 ? "D" : fi == 7'd2 ? "3" : fi == 7'd3 ? "*" : SP;
                     else begin ss = rescue == 2'd1 ? 5'd26 : rescue == 2'd2 ? 5'd10 : 5'd11; si = fi[3:0] + 4'd5; su = 1'b1; end
            F_BOOTBLD: begin ss = 5'd30; si = fi[3:0]; su = 1'b1; end
            F_BOOTVER: fch = hexd(VER[{3'd6 - fi[2:0], 2'b00} +: 4]);
            F_BOOTRX: begin                                // "C5 A ●   C5 B ●   C5 C ●", the dot green once the C5 is heard
                bo = fi >= 7'd18 ? 7'd18 : fi >= 7'd9 ? 7'd9 : 7'd0;
                bg_k = fi >= 7'd18 ? 2'd2 : fi >= 7'd9 ? 2'd1 : 2'd0;
                case (fi - bo)
                    7'd0: fch = "C"; 7'd1: fch = "5"; 7'd3: fch = 7'd65 + {5'd0, bg_k};
                    7'd5: begin fch = G_DOT; fgv = 1'b1; ffg = c5ok[bg_k] ? GREEN : (fresh[bg_k] || boot_ms >= 12'd1000) ? RED : GREY; end
                    default: fch = SP;
                endcase
            end
            F_BOOTSD: begin ss = HAS_DVR == 0 ? 5'd24 : ds2 == 2'd0 ? 5'd4 : ds2 == 2'd3 ? 5'd6 : 5'd5; si = fi[3:0]; su = 1'b1; end
            F_HZ90V: begin ss = 5'd27 + {3'd0, hz90_r}; si = fi[3:0] + 4'd1; su = 1'b1; end
            F_BRIGHTV: begin fch = fi[2:0] <= bright ? G_SEGON : G_SEGOFF; if (is_sel || is_edit) begin fgv = 1'b1; ffg = WHITE; end end
            F_CALV: begin
                if (cal_ms == 12'd0) fch = SP;
                else begin if (fi == 7'd5) fch = G_CHECK; else begin ss = 5'd12; si = fi[3:0] + 4'd4; su = 1'b1; end fgv = 1'b1; ffg = GREEN; end
            end
            F_REC: begin
                if (!(dvr && ds2 == 2'd2)) begin fch = 7'd0; fbv = 1'b1; fbg = BG_VIDEO; end
                else case (fi)
                    7'd0: begin fch = G_CAPL; fgv = 1'b1; ffg = PANELFG; fbv = 1'b1; fbg = BG_VIDEO; end
                    7'd1: begin fch = G_DOT; fgv = 1'b1; ffg = RED; end
                    7'd3: fch = "R"; 7'd4: fch = "E"; 7'd5: fch = "C";
                    7'd7: fch = rm_t != 4'd0 ? digit(rm_t) : SP;
                    7'd8: fch = digit(rm_o);
                    7'd9: fch = ":";
                    7'd10: fch = digit({1'b0, rs_t}); 7'd11: fch = digit(rs_o);
                    7'd12: begin fch = G_CAPR; fgv = 1'b1; ffg = PANELFG; fbv = 1'b1; fbg = BG_VIDEO; end
                    default: fch = SP;
                endcase
            end
            F_NOSIG: begin
                // no NO SIGNAL label: the picture (or snow) stays clear
                if (1'b1) begin fch = 7'd0; fbv = 1'b1; fbg = BG_VIDEO; end
                else if (fi == 7'd0 || fi == 7'd12) begin fch = fi == 7'd0 ? G_CAPL : G_CAPR; fgv = 1'b1; ffg = PANELFG; fbv = 1'b1; fbg = BG_VIDEO; end
                else if (fi >= 7'd2 && fi <= 7'd10) begin ss = 5'd13; si = fi[3:0] - 4'd2; su = 1'b1; end
                else fch = SP;
            end
            F_RXBAR: begin
                if (fi == 7'd0 || fi == 7'd13) begin fch = fi == 7'd0 ? G_CAPL : G_CAPR; fgv = 1'b1; ffg = PANELFG; fbv = 1'b1; fbg = BG_VIDEO; end
                else if (fi == 7'd2 || fi == 7'd6 || fi == 7'd10) begin
                    fch = bk == 2'd0 ? "A" : bk == 2'd1 ? "B" : "C"; fgv = 1'b1; ffg = fresh[bk] && bk <= mode ? WHITE : GREY;
                end else if (fi == 7'd3 || fi == 7'd7 || fi == 7'd11) begin
                    fgv = 1'b1; ffg = fresh[bk] && bk <= mode ? WHITE : GREY;
                    fch = !fresh[bk] ? G_BARS : st_sig[bk] >= 7'd88 ? G_BARS + 7'd4 : st_sig[bk] >= 7'd63 ? G_BARS + 7'd3 :
                          st_sig[bk] >= 7'd38 ? G_BARS + 7'd2 : st_sig[bk] >= 7'd13 ? G_BARS + 7'd1 : G_BARS;
                end else fch = SP;
            end
            // receivers page: video fields per second, real / predicted (gen_osd.py VIDFPS)
            F_VIDFPS: begin
                fch = SP; fgv = 1'b1; ffg = GREY;
                case (fi)
                    7'd0: fch = "V"; 7'd1: fch = "i"; 7'd2: fch = "d"; 7'd3: fch = "e"; 7'd4: fch = "o";
                    7'd6, 7'd7: begin
                        fch = fi == 7'd7 ? digit(O) : fr99 >= 7'd10 ? digit(T) : SP;
                        ffg = fr99 == 7'd0 ? RED : fp99 != 7'd0 ? AMBER : GREEN;
                    end
                    7'd8: fch = "/"; 7'd9: fch = "s";
                    7'd12: fch = "p"; 7'd13: fch = "r"; 7'd14: fch = "e"; 7'd15: fch = "d";
                    7'd17, 7'd18: begin
                        fch = fi == 7'd18 ? digit(O) : fp99 >= 7'd10 ? digit(T) : SP;
                        ffg = fp99 != 7'd0 ? AMBER : GREY;
                    end
                    default: fch = SP;
                endcase
            end
            F_RXROW: begin
                fch = SP;
                if (!fresh[rk]) begin
                    fgv = 1'b1; ffg = GREY;
                    if (fi == 7'd0) fch = rk == 2'd0 ? "A" : rk == 2'd1 ? "B" : "C";
                    else if (fi >= 7'd4 && fi <= 7'd8) fch = G_SEGOFF;
                    else if (fi == 7'd13 || fi == 7'd14 || fi == 7'd19 || fi == 7'd20) fch = "-";
                    else if (fi >= 7'd23 && fi <= 7'd25) begin ss = 5'd15; si = fi[3:0] - 4'd2; su = 1'b1; end
                end else begin
                    if (fi == 7'd0) fch = rk == 2'd0 ? "A" : rk == 2'd1 ? "B" : "C";
                    else if (fi >= 7'd4 && fi <= 7'd8) begin
                        fch = {1'b0, st_sig[rk]} > ({1'b0, fi} - 8'd4) * 8'd20 ? G_SEGON : G_SEGOFF; fgv = 1'b1; ffg = WHITE;
                    end else if (fi == 7'd12) fch = (cnr != 12'd0 && cn_neg && cn_db >= 8'd10) ? "-" : SP;
                    else if (fi == 7'd13) fch = cnr == 12'd0 ? "-" : cn_db >= 8'd10 ? digit(T) : (cn_neg && cn_db != 8'd0) ? "-" : SP;
                    else if (fi == 7'd14) fch = cnr == 12'd0 ? "-" : digit(O);
                    else if (fi >= 7'd18 && fi <= 7'd20 && native_applied[rk])
                        fch = fi == 7'd18 ? "N" : fi == 7'd19 ? "A" : "T";
                    else if (fi == 7'd18) fch = gn >= 8'd10 ? "G" : SP;
                    else if (fi == 7'd19) fch = gn >= 8'd10 ? digit(T) : "G";
                    else if (fi == 7'd20) fch = digit(O);
                    else if (fi >= 7'd23 && fi <= 7'd26) begin
                        fgv = 1'b1;
                        if (rk > mode) begin ffg = GREY; fch = fi == 7'd23 ? "I" : fi == 7'd24 ? "d" : fi == 7'd25 ? "l" : "e"; end
                        else if (st_flags[rk][3]) begin ffg = RED; fch = fi == 7'd23 ? "D" : fi == 7'd24 ? "C" : fi == 7'd25 ? "!" : SP; end
                        // locked; on a coarser IQ lane (STRONG LANE, flags bits 4..5) LkF / LkC
                        else if (st_flags[rk][0]) begin
                            ffg = GREEN;
                            fch = fi == 7'd23 ? "L" : st_flags[rk][5:4] == 2'd2 ? (fi == 7'd24 ? "o" : fi == 7'd25 ? "c" : "k") :
                                  fi == 7'd24 ? "k" : fi == 7'd25 ? (st_flags[rk][5:4] == 2'd1 ? "F" : "C") : SP;
                        end
                        else begin ffg = AMBER; fch = fi == 7'd23 ? "S" : fi == 7'd24 ? "e" : fi == 7'd25 ? "e" : "k"; end
                    end
                end
            end
            default: fch = SP;
        endcase
        if (su) fch = str(ss, si);
    end
    // resolve: the selection bar, edit colours
    reg [2:0] rfg; reg [1:0] rbg;
    always @(*) begin
        rfg = fgv ? ffg : tw[15:13];
        rbg = fbv ? fbg : tw[17:16];
        if (rbg == BG_BAR) begin
            rbg = is_sel ? (is_edit ? BG_DARK : BG_BAR) : BG_PANEL;
            if (is_sel && !is_edit && rfg == GREY) rfg = WHITE;
            if (is_edit && rfg == GREY) rfg = ACCENT;
        end
    end
    always @(posedge clk) begin
        osd_we <= !rst; osd_waddr <= wa1; osd_wdata <= {rbg, rfg, fch};
    end
endmodule
`default_nettype wire
