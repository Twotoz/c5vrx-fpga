"""C5VRX by Twotoz and the C5VRX contributors: writes fpga/rtl/rx/tables.vh,
the ROM functions of the TANG9K_DUAL RTL, from mrc_model.py (the single
source of the weight, inverse-root, cos/sin and arctangent tables).

    python hardware_experiments/tang9k_dual/fpga/model/gen_tables.py
"""
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'model'))
import mrc_model as m  # noqa: E402


def func(name, bits_in, bits_out, values, signed=False):
    sign = 'signed ' if signed else ''
    lines = [f'function automatic {sign}[{bits_out - 1}:0] {name};',
             f'    input [{bits_in - 1}:0] a;',
             '    begin',
             '        case (a)']
    for i, v in enumerate(values):
        v = int(v)
        lit = f"-{bits_out}'sd{-v}" if v < 0 else (f"{bits_out}'sd{v}" if signed else f"{bits_out}'d{v}")
        lines.append(f"            {bits_in}'d{i}: {name} = {lit};")
    lines += [f"            default: {name} = 0;", '        endcase', '    end', 'endfunction', '']
    return '\n'.join(lines)


def rom(name, bits, values):
    lines = [f'    {name}[{i}] = {bits}\'h{int(v) & ((1 << bits) - 1):0{(bits + 3) // 4}x};' for i, v in enumerate(values)]
    return lines


def main():
    head = ['// C5VRX by Twotoz and the C5VRX contributors: TANG9K_DUAL tables.',
            '// Generated by fpga/model/gen_tables.py from mrc_model.py; do not edit.', '']
    (HERE.parent / 'rtl' / 'rx' / 'tables.vh').write_text('\n'.join(head + [func('atan_lut', 5, 16, m.ATAN)]))
    body = head + ['// ROM contents (block RAM), included inside mrc_core.', 'initial begin']
    cs = [((int(c) & 255) << 8) | (int(sn) & 255) for c, sn in zip(m.COS, m.SIN)]
    body += rom('g_rom', 8, m.G) + rom('isq_rom', 8, m.ISQ) + rom('cs_rom', 16, cs)
    body += ['end', '']
    (HERE.parent / 'rtl' / 'rx' / 'rom_init.vh').write_text('\n'.join(body))
    # mrc3_core.v: the weight tables once, the cos/sin table per tracker
    gi = head + ['// weight ROMs (block RAM), included inside mrc3_core.', 'initial begin']
    gi += rom('g_rom', 8, m.G) + rom('isq_rom', 8, m.ISQ) + ['end', '']
    (HERE.parent / 'rtl' / 'rx' / 'rom_gi_init.vh').write_text('\n'.join(gi))
    csi = head + ['// cos/sin ROM (block RAM), included inside mrc3_trk.', 'initial begin']
    csi += rom('cs_rom', 16, cs) + ['end', '']
    (HERE.parent / 'rtl' / 'rx' / 'rom_cs_init.vh').write_text('\n'.join(csi))
    print('wrote rtl/rx/tables.vh, rom_init.vh, rom_gi_init.vh, rom_cs_init.vh')


if __name__ == '__main__':
    main()


def disc_rom():
    """rtl/rx/disc_rom.vh: mrc3_core's discriminator step and code per d (10 bit):
    step = d inside -312..384, else floor(d x 179 / 256); code = floor(cy x 205 / 1024)
    clipped to 0..63 with cy = floor((step x 105 + 32896) / 256)."""
    from pathlib import Path
    lines = ['// Generated by fpga/gen/gen_tables.py (disc_rom); do not edit.', 'initial begin']
    for a in range(1024):
        d = a - 1024 if a >= 512 else a
        step = d if -312 <= d <= 384 else (d * 179) >> 8
        cy = (step * 105 + 32896) >> 8
        code = 0 if cy < 0 else min(63, ((cy & 511) * 205) >> 10)
        lines.append(f"    disc[{a}] = 16'h{((step & 1023) << 6) | code:04x};")
    lines.append('end')
    (Path(__file__).resolve().parent.parent / 'rtl' / 'rx' / 'disc_rom.vh').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    disc_rom()
