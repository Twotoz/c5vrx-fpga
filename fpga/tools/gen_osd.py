"""Triversity: OSD tables for the FPGA (writes rtl/font_init.vh, rtl/osd_init.vh).

font_init.vh  8 x 16 glyphs of ASCII 0..127, rendered from DejaVu Sans Mono Bold
              (thresholded; any monospace TTF works: --font)
osd_init.vh   the OSD template (30 rows x 50 columns, 16-bit words: field id
              << 8 | literal char or field character index) and the channel
              frequency ROM (C5VRX's channel table, firmware/main/rf.c)

    python fpga/tools/gen_osd.py
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
RTL = HERE.parent / 'rtl'
COLS, ROWS = 50, 30
FREQS = [5658, 5695, 5732, 5769, 5806, 5843, 5880, 5917, 5865, 5845, 5825, 5805, 5785, 5765, 5745, 5725,
         5733, 5752, 5771, 5790, 5809, 5828, 5847, 5866, 5705, 5685, 5665, 5645, 5885, 5905, 5925, 5945,
         5740, 5760, 5780, 5800, 5820, 5840, 5860, 5880, 5362, 5399, 5436, 5473, 5510, 5547, 5584, 5621]
# field ids (menu.v): width
F = dict(CHNAME=(1, 2), FREQ=(2, 4), BARS_A=(3, 5), BARS_B=(4, 5), BARS_C=(5, 5), STD=(6, 4), MODE=(7, 3),
         CURSOR=(8, 1), GAINMODE=(9, 5), AFC=(10, 3), BRIGHT=(11, 1), GAIN_A=(12, 2), GAIN_B=(13, 2),
         GAIN_C=(14, 2), CN_A=(15, 3), CN_B=(16, 3), CN_C=(17, 3), FLAGS_A=(18, 3), FLAGS_B=(19, 3),
         FLAGS_C=(20, 3), SCAN=(21, 9), NOVIDEO=(22, 8))
ITEMS = ['CHANNEL', 'SCAN', 'MODE', 'GAIN', 'AFC', 'BRIGHT', 'CALIBRATE', 'EXIT']
ITEM_ROW0 = 3


def template():
    t = [[0] * COLS for _ in range(ROWS)]

    def put(r, c, text):
        for k, ch in enumerate(text):
            t[r][c + k] = ord(ch)

    def field(r, c, name, index=None):
        fid, w = F[name]
        for k in range(w):
            t[r][c + k] = fid << 8 | (k if index is None else index)
        return c + w
    # row 0: status, always shown
    put(0, 0, ' ' * COLS)
    c = field(0, 1, 'CHNAME'); c = field(0, c + 1, 'FREQ')
    put(0, 10, 'A'); field(0, 11, 'BARS_A'); put(0, 17, 'B'); field(0, 18, 'BARS_B')
    put(0, 24, 'C'); field(0, 25, 'BARS_C'); field(0, 32, 'STD'); field(0, 37, 'MODE')
    # menu rows (shown while the menu is open)
    put(2, 1, ' TRIVERSITY' + ' ' * 27)
    for k, name in enumerate(ITEMS):
        r = ITEM_ROW0 + k
        put(r, 1, ' ' * 38)
        field(r, 2, 'CURSOR', k)
        put(r, 4, name)
    field(3, 15, 'CHNAME'); field(3, 18, 'FREQ'); put(3, 23, 'MHZ')
    field(4, 15, 'SCAN'); field(5, 15, 'MODE'); field(6, 15, 'GAINMODE'); field(7, 15, 'AFC')
    field(8, 15, 'BRIGHT'); put(9, 15, 'C5 FILTER + DC')
    put(12, 1, ' ' * 38)
    put(12, 2, 'C5  SIGNAL  GAIN  C/N  FLAGS')
    for k, s in enumerate('ABC'):
        r = 13 + k
        put(r, 1, ' ' * 38)
        put(r, 2, s)
        field(r, 6, 'BARS_' + s); field(r, 14, 'GAIN_' + s); field(r, 19, 'CN_' + s); field(r, 25, 'FLAGS_' + s)
    put(17, 1, ' ' * 38)
    put(17, 2, 'UP/DOWN: MOVE  SELECT: CHANGE  HOLD: CLOSE')
    # NO VIDEO, centred, shown without lock
    field(22, 21, 'NOVIDEO')
    return t


def font(path):
    f = ImageFont.truetype(path, 15)
    out = []
    for code in range(128):
        img = Image.new('L', (8, 16), 0)
        if 32 <= code < 127:
            d = ImageDraw.Draw(img)
            d.text((0, -1), chr(code), font=f, fill=255)
        px = img.load()
        for y in range(16):
            out.append(sum((1 << (7 - x)) for x in range(8) if px[x, y] > 110))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--font', default='/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf')
    a = ap.parse_args()
    head = ['// Generated by fpga/tools/gen_osd.py; do not edit.']
    g = font(a.font)
    (RTL / 'font_init.vh').write_text('\n'.join(head + ['initial begin'] +
        [f'    font[{i}] = 8\'h{v:02x};' for i, v in enumerate(g)] + ['end', '']))
    t = template()
    lines = head + ['initial begin']
    lines += [f'    tmpl[{r * COLS + c}] = 16\'h{t[r][c]:04x};' for r in range(ROWS) for c in range(COLS)]
    def bcd(n): return int(str(n), 16)
    lines += [f'    freq[{i}] = 16\'h{bcd(f):04x};' for i, f in enumerate(FREQS)]
    lines += ['end', '']
    (RTL / 'osd_init.vh').write_text('\n'.join(lines))
    print('wrote rtl/font_init.vh, rtl/osd_init.vh')


if __name__ == '__main__':
    main()
